let calendar_date s =
  let bad () = invalid_arg "expected YYYY-MM-DD" in
  if String.length s <> 10 || s.[4] <> '-' || s.[7] <> '-' then bad ();
  String.iteri (fun i c ->
    if i <> 4 && i <> 7 && (c < '0' || c > '9') then bad ()) s;
